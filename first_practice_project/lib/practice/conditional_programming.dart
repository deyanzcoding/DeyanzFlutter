//conditional programming

void main() {
  var a = 100;
  var b = 200;

  if (a > b) {
    print("A is greater :  $a");
  } else {
    print("B is greater :  $b");
  }

  //for-loop
  for (int i = 0; i <= 10; i++) {
    print("hello world of index : $i");
  }

  //while-loop
  int c = 0;
  while (c <= 10) {
    print("Deyan");
    c++;
  }

  //do-while-loop
  var idx = 10;
  do {
    print("Hasnain");
    idx--;
  } while (idx != 0);
}
